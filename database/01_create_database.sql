-- รันตอนต่ออยู่กับฐานข้อมูล "postgres" ไม่ใช่ rfid-system เพราะยังไม่มี
-- ใช้ผู้ใช้ที่มีสิทธิ์สร้างฐานข้อมูล เช่น postgres
--
-- CREATE DATABASE มีข้อจำกัด 2 อย่าง
--   1. รันใน transaction ไม่ได้ ใน pgAdmin ให้ปิด auto-rollback หรือรันทีละคำสั่ง
--   2. ไม่มี IF NOT EXISTS ถ้ามีฐานข้อมูลอยู่แล้วจะขึ้น error ว่า already exists
--      ไม่เป็นไร ข้ามไปรัน 02_schema.sql ต่อได้เลย
--
-- ชื่อมีขีดกลาง จึงต้องครอบด้วยอัญประกาศคู่ทุกครั้งที่อ้างถึง

SET client_encoding = 'UTF8';

CREATE DATABASE "rfid-system"
    WITH
    ENCODING = 'UTF8'
    -- template0 รับประกันว่าได้ UTF8 จริง ไม่ว่า template1 ของเครื่องนั้นจะตั้งไว้แบบไหน
    -- ต้องเป็น UTF8 เพราะมีทั้งชื่อสินค้าและข้อความภาษาไทยเก็บอยู่
    TEMPLATE = template0;
