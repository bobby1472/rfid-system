#include "secrets.h"

// ---------- เซิร์ฟเวอร์ ----------
// IP ของเครื่องที่รัน backend (ดูด้วยคำสั่ง ipconfig) ห้ามใส่ localhost
// เพราะ localhost ของ ESP8266 คือตัวมันเอง ไม่ใช่คอมพิวเตอร์
#define API_HOST  "192.168.1.150"
#define API_PORT  7777

// ---------- รหัสเครื่องอ่าน ----------
// ต้องตรงกับรหัสในหน้าเว็บ เช่น WC05 WC07 WC08 WC09
// เครื่องใหม่ที่ยังไม่มีในระบบ เซิร์ฟเวอร์จะเพิ่มให้เองอัตโนมัติ
#define DEVICE_ID  "WC07"

// ---------- ขา ----------
#define SS_PIN   D8    // RC522 SDA/SS
#define SDA_PIN  D2    // I2C ของจอ LCD
#define SCL_PIN  D1
#define BUZZER   D0    // low-level trigger, จ่ายไฟจาก VIN (5V)

// ---------- เวลาต่าง ๆ (มิลลิวินาที) ----------
// หมดเวลารอเซิร์ฟเวอร์ตอบ สั้น ๆ พอ เพราะคนยืนรอหน้าเครื่องอยู่
#define HTTP_TIMEOUT_MS   3000

// รอ WiFi ตอนบูตได้นานหน่อย ช่วงนี้ยังไม่มีใครมาแตะบัตร
#define WIFI_BOOT_TIMEOUT_MS  10000

// เว้นระยะก่อนสั่งต่อ WiFi ใหม่ ระหว่างนี้ auto-reconnect ทำงานเป็นพื้นหลังอยู่
#define WIFI_RETRY_MS     15000

// ถ้า RC522 ยังไม่ตอบตอนบูต จะลอง init ใหม่ทุกช่วงเวลานี้
#define RC522_RETRY_MS     3000

// ตรวจว่า RC522 ยังพร้อมอ่านบัตรทุก ๆ เท่านี้ ถ้าค้างจะ init ใหม่ให้เอง
// กันอาการเปิดทิ้งไว้ข้ามคืนแล้วจอค้างที่ Ready แต่แตะบัตรไม่ติด
#define RC522_HEALTH_MS    10000

// init RC522 ใหม่แบบป้องกันไว้ก่อนทุก ๆ เท่านี้ แม้ผลตรวจจะปกติ (0 = ปิด)
// ค่านี้คือเวลานานสุดที่เครื่องอาจค้างในกรณีที่ RC522 ยังตอบ register ถูกแต่อ่านบัตรไม่ได้
// ซึ่งการตรวจสุขภาพข้างบนจับไม่ได้ init ใช้เวลาราว 50ms และทำตอนไม่มีบัตรเท่านั้น
#define RC522_REINIT_MS    60000UL

// รีสตาร์ทบอร์ดเองเมื่อเปิดครบเท่านี้ เป็นตาข่ายรองรับชั้นสุดท้าย (0 = ปิด)
// ระหว่างรีสตาร์ทราว 10 วินาทีจะแตะบัตรไม่ได้
#define DAILY_RESTART_MS   86400000UL

// ไฟติดค้างนานเท่าไหร่ตอนบัตรผ่าน ระหว่างนี้จะยังอ่านบัตรใบถัดไปไม่ได้
// 1 วินาทีกำลังดีสำหรับประตู จอ LCD ค้างผลไว้ให้อยู่แล้ว
#define LED_OK_MS  1000

// ประกาศตัวเองให้เซิร์ฟเวอร์รู้ว่ายังออนไลน์ ทุก 5 นาที
#define ANNOUNCE_INTERVAL_MS  300000

// ถ้าส่งสถานะ RC522 ที่เปลี่ยนไปไม่ถึงเซิร์ฟเวอร์ ให้ลองส่งใหม่ทุก ๆ เท่านี้จนกว่าจะรับ
// ไม่ถี่กว่านี้ เพราะถ้าเซิร์ฟเวอร์ไม่ตอบ การส่งแต่ละครั้งจะค้างรอได้ถึง HTTP_TIMEOUT_MS
#define ANNOUNCE_RETRY_MS  15000

// เวอร์ชันเฟิร์มแวร์ ส่งไปกับ announce เผื่อไล่ดูว่าเครื่องไหนยังใช้ของเก่า
#define FIRMWARE_VERSION  "1.3.2"
